def apply(path: Path, fixes: list[tuple[str, str]], label: str) -> tuple[int, int]:
    """
    对单个文件执行替换。

    参数:
        path: 目标文件。
        fixes: (旧串, 新串) 列表。
        label: 日志用的名称。

    返回:
        (命中数, 未命中数)。
    """
    text = path.read_text(encoding="utf-8")
    hit, miss = 0, 0
    missed: list[str] = []
    for old, new in fixes:
        if old == new:
            continue
        if old in text:
            text = text.replace(old, new)
            hit += 1
        else:
            miss += 1
            missed.append(old[:50])
    path.write_text(text, encoding="utf-8")
    print(f"[{label}] 命中 {hit} 条，未命中 {miss} 条")
    for m in missed:
        print("    未命中:", m)
    return hit, miss


def main() -> int:
    """执行全部替换。"""
    targets = [
        (ROOT / "src" / "report_generator.py", "报告"),
        (ROOT / "src" / "ppt_generator.py", "PPT"),
    ]
    total_miss = 0
    for path, label in targets:
        if not path.exists():
            print(f"文件不存在: {path}")
            return 1
        _, miss = apply(path, DASH_FIXES, f"{label}-破折号")
        total_miss += miss
        _, miss2 = apply(path, TONE_FIXES, f"{label}-语气")
        total_miss += miss2

    print(f"\n合计未命中 {total_miss} 条")
    return 0


if __name__ == "__main__":
    sys.exit(main())