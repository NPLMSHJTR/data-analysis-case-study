def save_market_tables() -> dict:
    """
    把市场事实、类型热度与档期窗口写为 CSV，供报告与推荐模块引用。

    返回:
        含三张表行数与文件名的字典。
    """
    facts = pd.DataFrame(MARKET_FACTS)
    facts.to_csv(TABLE_DIR / "q5_market_facts.csv", index=False, encoding="utf-8-sig")

    heat = pd.DataFrame(
        [{"主类型": k, "市场热度": v} for k, v in GENRE_HEAT.items()]
    ).sort_values("市场热度", ascending=False)
    heat.to_csv(TABLE_DIR / "q5_genre_heat.csv", index=False, encoding="utf-8-sig")

    windows = pd.DataFrame(RELEASE_WINDOWS)
    windows.to_csv(TABLE_DIR / "q5_release_windows.csv", index=False, encoding="utf-8-sig")

    logger.info(
        "市场数据已保存：事实 %d 条，类型热度 %d 项，档期窗口 %d 个",
        len(facts), len(heat), len(windows),
    )
    return {
        "facts": len(facts),
        "genre_heat": len(heat),
        "windows": len(windows),
        "note": GENRE_HEAT_NOTE,
    }