def get_note(slide_no: int) -> str:
    """
    取指定页码的备注文本。

    参数:
        slide_no: 页码，从 1 开始。

    返回:
        备注文本；页码越界时返回空串，避免生成时报错。
    """
    return NOTES.get(slide_no, "")


def apply_notes(prs) -> int:
    """
    把备注写入演示文稿的每一页。

    参数:
        prs: python-pptx 的 Presentation 对象。

    返回:
        实际写入的页数。
    """
    count = 0
    for idx, slide in enumerate(prs.slides, start=1):
        text = get_note(idx)
        if not text:
            continue
        slide.notes_slide.notes_text_frame.text = text
        count += 1
    return count