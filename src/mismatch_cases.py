"""
src/mismatch_cases.py
=====================
从候选池中抽取最终 20 条典型不一致样本，并写入逐条复核结论。

为什么复核结论要单独写一份
--------------------------
候选池由算法按不一致程度排序选出，但「这条评论为什么矛盾」必须由人判断。
本项目采用的做法是：先由脚本按规则抽出候选（覆盖四类情况），
再由研究者逐条阅读原文、填写「真实不一致 / 复杂情感 / 模型误判」与成因说明。
本模块只负责「抽取 + 落表」，不自动生成任何复核结论。

复核结论的取值含义
------------------
真实不一致  文本情感方向与星级确实相反，如五星配通篇差评
复杂情感    反讽、以贬词表喜爱、正负并存，不能简单归为矛盾
模型误判    文本真实情感与星级一致，是情感模型判断错误
"""

